/*
 * Stores expected distance data from `unitig_from` to `unitig_to` for all the tested SGGs.
 *
 * The `sgg_distances` vector contains one expected distance per tested SGG in SGG edges filename order.
*/
struct ExpectedDistanceData {
    std::size_t unitig_from;
    std::size_t unitig_to;
    std::vector<std::int64_t> sgg_distances;

    // Returns the number of SGGs where the unitig pair was connected.
    std::size_t count() const noexcept {
        std::size_t count = 0;

        for (const auto distance : sgg_distances) {
            count += static_cast<std::size_t>(distance != INF_DISTANCE);
        }

        return count;
    }

    // Returns the mean distance.
    double mean_distance() const noexcept {
        assert(count() >= 1);

        double sum = 0.0;

        for (const auto distance : sgg_distances) {
            if (distance != INF_DISTANCE) {
                sum += static_cast<double>(distance);
            }
        }

        return sum / static_cast<double>(count());
    }

    // Returns the sample variance.
    double sample_variance() const noexcept {
        const auto cnt = count();

        assert(cnt >= 2);

        // Compute the mean first to reduce cancellation errors exceeding the test harness's 1e-6 tolerance.
        const auto mean = mean_distance();
        double squared_deviation_sum = 0.0;

        for (const auto distance : sgg_distances) {
            if (distance != INF_DISTANCE) {
                const auto deviation = static_cast<double>(distance) - mean;
                squared_deviation_sum += deviation * deviation;
            }
        }

        return squared_deviation_sum / static_cast<double>(cnt - 1);
    }

    // Returns the minimum distance.
    std::int64_t min_distance() const noexcept {
        assert(count() >= 1);

        auto minimum = static_cast<std::int64_t>(INF_DISTANCE);

        for (const auto distance : sgg_distances) {
            if (distance != INF_DISTANCE) {
                minimum = std::min(minimum, distance);
            }
        }

        return minimum;
    }

    // Returns the maximum distance.
    std::int64_t max_distance() const noexcept {
        assert(count() >= 1);

        std::int64_t maximum{};

        for (const auto distance : sgg_distances) {
            if (distance != INF_DISTANCE) {
                maximum = std::max(maximum, distance);
            }
        }

        return maximum;
    }

    // Returns the lower median of the distances.
    std::int64_t median_distance() const {
        assert(count() >= 1);

        std::vector<std::int64_t> distances;

        for (const auto distance : sgg_distances) {
            if (distance != INF_DISTANCE) {
                distances.push_back(distance);
            }
        }

        std::sort(distances.begin(), distances.end());

        return distances[(distances.size() - 1) / 2];
    }
};

